/**
 * dsh-harness-launcher — Host half.
 *
 * Serves a tiny loopback JSON API under `/plugins/harness-launcher/api` and owns
 * every privileged step of the desktop launcher:
 *
 * - `GET  /url`    plain-text authenticated browser URL (the launcher's probe).
 * - `GET  /status` JSON state for the sidebar panel.
 * - `POST /icon`   writes the launcher scripts and creates the desktop shortcut.
 * - `POST /open`   opens the running UI in the default browser.
 * - `POST /restart` / `POST /close` detach `wscript` to restart or stop this Host.
 *
 * Restart and close run in a detached `wscript.exe`, never in this process: the
 * work is killing the process that is answering the request, and something has
 * to survive it to start the next one.
 */
import { execFile, spawn } from 'node:child_process';
import { access, copyFile, mkdir, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

/** Stable cordis plugin name. */
export const name = 'harness-launcher';
/** Services required before mounting. */
export const inject = ['webServer'];

const API_BASE = '/plugins/harness-launcher/api';
const PKG_DIR = dirname(fileURLToPath(import.meta.url));
const SHORTCUT_NAME = 'DeepSeek Harness';
const LAUNCHER_EXE = join(process.env.SystemRoot ?? 'C:\\Windows', 'System32', 'wscript.exe');
const execFileAsync = promisify(execFile);

/** Resolve the profile name this Host was booted with. */
function resolveProfile() {
  if (process.env.DSH_PROFILE) return process.env.DSH_PROFILE;
  const argv = process.argv;
  const index = argv.indexOf('--profile');
  if (index >= 0 && argv[index + 1] !== undefined && !argv[index + 1].startsWith('-')) return argv[index + 1];
  return 'web';
}

/** Absolute directory holding the generated launcher scripts and icon. */
function launcherDir() {
  const base = process.env.LOCALAPPDATA ?? join(homedir(), 'AppData', 'Local');
  return join(base, 'dsh-harness-launcher');
}

/** Locate the `dsh` command shim so the launcher never depends on the caller's PATH. */
async function resolveDshCommand() {
  const candidates = ['dsh.cmd', 'dsh.exe', 'dsh'];
  for (const candidate of candidates) {
    try {
      const { stdout } = await execFileAsync('where.exe', [candidate], { windowsHide: true, timeout: 10_000 });
      const first = String(stdout)
        .split(/\r?\n/u)
        .map((line) => line.trim())
        .find((line) => line !== '');
      if (first !== undefined) return first;
    } catch {
      // `where` exits 1 when nothing matches; try the next candidate.
    }
  }
  throw new Error('Could not find `dsh` on PATH; install DeepSeek Harness or add it to PATH.');
}

/** The real Desktop folder, honouring a redirected (OneDrive) profile. */
async function resolveDesktop() {
  if (process.platform !== 'win32') return join(homedir(), 'Desktop');
  try {
    const { stdout } = await execFileAsync(
      'powershell.exe',
      ['-NoProfile', '-NonInteractive', '-Command', "[Environment]::GetFolderPath('Desktop')"],
      { windowsHide: true, timeout: 15_000 },
    );
    const value = String(stdout).trim();
    if (value !== '') return value;
  } catch {
    // Fall through to the conventional location.
  }
  return join(homedir(), 'Desktop');
}

/** Quote one PowerShell single-quoted literal. */
function psLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

/** Quote one VBScript double-quoted literal (contents only). */
function vbsLiteral(value) {
  return String(value).replaceAll('"', '""');
}

/**
 * The generated launcher. One file serves every entry point: the desktop icon
 * runs `open`, the Host runs `restart`/`close` with the pid to stop.
 */
function launcherScript({ apiUrl, dshCommand, profile, logPath }) {
  return `Option Explicit
' Generated by dsh-harness-launcher. Regenerating the desktop icon rewrites this file.

Const API_URL = "${vbsLiteral(apiUrl)}"
Const DSH_CMD = "${vbsLiteral(dshCommand)}"
Const DSH_PROFILE = "${vbsLiteral(profile)}"
Const LOG_PATH = "${vbsLiteral(logPath)}"
Const START_TIMEOUT_MS = 90000
Const STOP_TIMEOUT_MS = 20000

Dim shell
Set shell = CreateObject("WScript.Shell")

Dim mode
If WScript.Arguments.Count > 0 Then
  mode = LCase(WScript.Arguments(0))
Else
  mode = "open"
End If

Dim target
If mode = "restart" Or mode = "close" Then
  StopHost
  If mode = "restart" Then StartHost
  WScript.Quit 0
End If

target = ProbeUrl()
If target <> "" Then
  OpenUrl target
  WScript.Quit 0
End If

Log "not reachable; starting it hidden"
StartHost

Sub StartHost()
  shell.Run Quote(DSH_CMD) & " --profile " & DSH_PROFILE & " --no-open", 0, False
  Dim waited, url
  waited = 0
  Do While waited < START_TIMEOUT_MS
    WScript.Sleep 500
    waited = waited + 500
    url = ProbeUrl()
    If url <> "" Then
      Log "ready after " & waited & " ms"
      OpenUrl url
      Exit Sub
    End If
  Loop
  Log "did not answer within " & START_TIMEOUT_MS & " ms"
  MsgBox "DeepSeek Harness did not start within " & (START_TIMEOUT_MS \\ 1000) & " seconds." & vbCrLf & vbCrLf & "Log: " & LOG_PATH, vbExclamation, "DeepSeek Harness"
End Sub

Sub StopHost()
  Dim pid, waited
  If WScript.Arguments.Count > 1 Then pid = WScript.Arguments(1) Else pid = ""
  Log "stopping pid " & pid
  If pid <> "" Then shell.Run "taskkill /F /PID " & pid, 0, True
  waited = 0
  Do While waited < STOP_TIMEOUT_MS
    If ProbeUrl() = "" Then Exit Do
    WScript.Sleep 300
    waited = waited + 300
  Loop
  If ProbeUrl() <> "" Then
    Log "warning: the service still answers after the stop request"
    MsgBox "DeepSeek Harness is still running after the stop request." & vbCrLf & vbCrLf & "Log: " & LOG_PATH, vbExclamation, "DeepSeek Harness"
  Else
    Log "stopped after " & waited & " ms"
  End If
End Sub

Function ProbeUrl()
  ProbeUrl = ""
  On Error Resume Next
  Dim http, body, head
  Set http = CreateObject("MSXML2.ServerXMLHTTP.6.0")
  If Err.Number <> 0 Then
    Err.Clear
    Exit Function
  End If
  http.setTimeouts 1000, 1000, 2000, 2000
  http.open "GET", API_URL, False
  http.send
  If Err.Number = 0 Then
    If http.Status = 200 Then
      body = Trim(http.responseText)
      If Len(body) > 4 Then
        head = LCase(Left(body, 4))
        If head = "http" Then ProbeUrl = body
      End If
    End If
  End If
  Err.Clear
End Function

Sub OpenUrl(address)
  On Error Resume Next
  shell.Run address, 1, False
  If Err.Number <> 0 Then
    Log "could not open " & address
    MsgBox "Could not open " & address, vbExclamation, "DeepSeek Harness"
  End If
  Err.Clear
End Sub

Function Quote(value)
  Quote = """" & value & """"
End Function

Sub Log(message)
  On Error Resume Next
  Dim fso, file, folder
  Set fso = CreateObject("Scripting.FileSystemObject")
  folder = fso.GetParentFolderName(LOG_PATH)
  If Not fso.FolderExists(folder) Then fso.CreateFolder folder
  If fso.FileExists(LOG_PATH) Then
    If fso.GetFile(LOG_PATH).Size > 262144 Then fso.DeleteFile LOG_PATH, True
  End If
  Set file = fso.OpenTextFile(LOG_PATH, 8, True)
  file.WriteLine Now & "  [" & mode & "]  " & message
  file.Close
  Err.Clear
End Sub
`;
}

/** Read and validate a JSON body, bounded to keep a bad caller from buffering forever. */
async function readJsonBody(req) {
  let data = '';
  for await (const chunk of req) {
    data += typeof chunk === 'string' ? chunk : chunk.toString('utf8');
    if (data.length > 65_536) throw new Error('request body too large');
  }
  return data === '' ? {} : JSON.parse(data);
}

/** Only a request arriving on the loopback host may drive this API. */
function isLoopbackRequest(req) {
  const host = String(req.headers?.host ?? '').replace(/:\d+$/u, '').toLowerCase();
  return host === 'localhost' || host === '127.0.0.1' || host === '[::1]' || host === '::1';
}

function writeJson(res, status, body) {
  res.writeHead(status, {
    'content-type': 'application/json; charset=utf-8',
    'cache-control': 'no-store',
  });
  res.end(JSON.stringify(body));
}

function writeText(res, status, text) {
  res.writeHead(status, {
    'content-type': 'text/plain; charset=utf-8',
    'cache-control': 'no-store',
  });
  res.end(text);
}

function writeOk(res, value) {
  writeJson(res, 200, { ok: true, value });
}

function writeError(res, error, status = 400) {
  writeJson(res, status, {
    ok: false,
    error: { code: error.code ?? 'error', message: error.message ?? String(error) },
  });
}

/** Launch a detached helper so the caller's process is not waiting on itself. */
function spawnDetached(file, args) {
  const child = spawn(file, args, { detached: true, stdio: 'ignore', windowsHide: true });
  child.unref();
}

export function apply(ctx) {
  const profile = resolveProfile();
  const dir = launcherDir();
  const scriptPath = join(dir, 'launcher.vbs');
  const iconPath = join(dir, 'icon.ico');
  const logPath = join(dir, 'launcher.log');

  let dshCommandPromise;
  const dshCommand = () => {
    dshCommandPromise ??= resolveDshCommand();
    return dshCommandPromise;
  };
  let desktopPromise;
  const desktop = () => {
    desktopPromise ??= resolveDesktop();
    return desktopPromise;
  };

  const origin = () => ctx.webServer.getOrigin();
  // Resolved per request, never cached: this plugin can apply before the
  // connection service exists, and a cached `undefined` mints no launch token,
  // which would hand the launcher an unauthenticated URL.
  const browserUrl = () => {
    const base = origin();
    const connection = ctx.get('connection');
    return typeof connection?.authenticatedUrl === 'function' ? connection.authenticatedUrl(base) : base;
  };

  const collectStatus = async () => {
    const [resolvedDsh, desktopPath] = await Promise.all([dshCommand().catch(() => null), desktop()]);
    const shortcut = join(desktopPath, `${SHORTCUT_NAME}.lnk`);
    let iconExists = false;
    try {
      await access(shortcut);
      iconExists = true;
    } catch {
      iconExists = false;
    }
    const url = browserUrl();
    let parsed;
    try {
      parsed = new URL(url);
    } catch {
      parsed = undefined;
    }
    return {
      platform: process.platform,
      pid: process.pid,
      profile,
      origin: origin(),
      url,
      port: parsed?.port ?? '',
      dshCommand: resolvedDsh,
      launcherDir: dir,
      launcherScript: scriptPath,
      logPath,
      icon: { name: SHORTCUT_NAME, path: shortcut, desktop: desktopPath, exists: iconExists },
    };
  };

  /** Write the launcher script and the icon copy the shortcut points at. */
  const writeRuntime = async () => {
    const [resolvedDsh] = await Promise.all([dshCommand()]);
    await mkdir(dir, { recursive: true });
    const text = launcherScript({
      apiUrl: `${origin()}${API_BASE}/url`,
      dshCommand: resolvedDsh,
      profile,
      logPath,
    });
    await writeFile(scriptPath, text, 'utf8');
    try {
      await copyFile(join(PKG_DIR, 'icon.ico'), iconPath);
    } catch {
      // A missing package icon is not fatal: the shortcut falls back to wscript's own glyph.
    }
  };

  /** Create (or refresh) the desktop shortcut through WScript.Shell. */
  const createShortcut = async () => {
    const desktopPath = await desktop();
    const shortcut = join(desktopPath, `${SHORTCUT_NAME}.lnk`);
    const script = [
      "$ErrorActionPreference = 'Stop'",
      `$link = Join-Path ${psLiteral(desktopPath)} ${psLiteral(`${SHORTCUT_NAME}.lnk`)}`,
      '$shell = New-Object -ComObject WScript.Shell',
      '$item = $shell.CreateShortcut($link)',
      `$item.TargetPath = ${psLiteral(LAUNCHER_EXE)}`,
      `$item.Arguments = ${psLiteral(`//nologo "${scriptPath}" open`)}`,
      `$item.WorkingDirectory = ${psLiteral(dir)}`,
      `$item.IconLocation = ${psLiteral(`${iconPath},0`)}`,
      `$item.Description = ${psLiteral('Start or open DeepSeek Harness')}`,
      '$item.WindowStyle = 7',
      '$item.Save()',
      'Write-Output $link',
    ].join('\n');
    const { stdout } = await execFileAsync(
      'powershell.exe',
      ['-NoProfile', '-NonInteractive', '-ExecutionPolicy', 'Bypass', '-Command', script],
      { windowsHide: true, timeout: 30_000 },
    );
    return String(stdout).trim() || shortcut;
  };

  const handler = async (req, res) => {
    if (!isLoopbackRequest(req)) {
      writeError(res, { code: 'forbidden', message: 'only loopback clients may drive the launcher' }, 403);
      return;
    }
    const pathname = new URL(req.url ?? '/', 'http://dsh.internal').pathname;
    const method = pathname.startsWith(`${API_BASE}/`) ? pathname.slice(API_BASE.length + 1) : undefined;

    // The launcher probe: unauthenticated by design, and only ever a URL.
    if (method === 'url') {
      if (req.method !== 'GET' && req.method !== 'HEAD') {
        writeError(res, { code: 'method-error', message: 'GET only' }, 405);
        return;
      }
      writeText(res, 200, browserUrl());
      return;
    }

    if (method === undefined || method.includes('/')) {
      writeError(res, { code: 'not-found', message: 'unknown method' }, 404);
      return;
    }

    // Mutations require the custom header: a cross-origin page cannot send it
    // without a preflight this server never approves.
    if (req.method !== 'GET') {
      if (req.method !== 'POST') {
        writeError(res, { code: 'method-error', message: 'POST only' }, 405);
        return;
      }
      if (req.headers['x-dsh-launcher'] === undefined) {
        writeError(res, { code: 'forbidden', message: 'missing x-dsh-launcher header' }, 403);
        return;
      }
    }

    try {
      switch (method) {
        case 'status': {
          writeOk(res, await collectStatus());
          return;
        }
        case 'icon': {
          if (process.platform !== 'win32') {
            writeOk(res, { ok: false, reason: `desktop shortcuts are Windows-only; this Host is ${process.platform}` });
            return;
          }
          await readJsonBody(req);
          await writeRuntime();
          const path = await createShortcut();
          writeOk(res, { ok: true, path, launcherDir: dir });
          return;
        }
        case 'open': {
          await readJsonBody(req);
          spawnDetached('rundll32.exe', ['url.dll,FileProtocolHandler', browserUrl()]);
          writeOk(res, { ok: true, url: browserUrl() });
          return;
        }
        case 'restart':
        case 'close': {
          await readJsonBody(req);
          await writeRuntime();
          spawnDetached(LAUNCHER_EXE, ['//nologo', scriptPath, method, String(process.pid)]);
          writeOk(res, { ok: true, pid: process.pid, action: method });
          return;
        }
        default:
          writeError(res, { code: 'not-found', message: `unknown method "${method}"` }, 404);
      }
    } catch (error) {
      writeError(res, {
        code: 'internal',
        message: error instanceof Error ? error.message : String(error),
      }, 500);
    }
  };

  ctx.effect(
    () => ctx.webServer.register({ kind: 'prefix', path: API_BASE, handler }),
    'dsh-harness-launcher: loopback launcher api',
  );
}
